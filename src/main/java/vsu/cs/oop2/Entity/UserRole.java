package vsu.cs.oop2.Entity;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

/**
 * ПЕРЕЧИСЛЕНИЕ РОЛЕЙ ПОЛЬЗОВАТЕЛЕЙ СИСТЕМЫ
 *
 * Определяет возможные роли пользователей и соответствующие
 * authority строки для Spring Security.
 *
 * Роли используются для:
 * - Контроля доступа к функционалу (авторизация)
 * - Определения прав пользователей
 * - Настройки видимости элементов интерфейса
 * @see org.springframework.security.core.GrantedAuthority
 */
@Getter
@RequiredArgsConstructor
public enum UserRole {
    /**
     * РОЛЬ ОБЫЧНОГО ПОЛЬЗОВАТЕЛЯ
     *
     * Базовая роль для всех зарегистрированных пользователей.
     * Разрешает:
     * - Просмотр и поиск треков
     * - Загрузку собственных треков
     * - Ставление лайков
     *
     * Ограничения:
     * - Не может удалять чужие треки
     * - Не имеет доступа к административной панели
     *
     * @apiNote Является ролью по умолчанию при регистрации.
     *          Authority: "ROLE_USER"
     */
    USER("ROLE_USER"),

    /**
     * РОЛЬ АДМИНИСТРАТОРА СИСТЕМЫ
     *
     * Роль с максимальными привилегиями.
     * Разрешает всё, что может обычный пользователь, плюс:
     * - Полный доступ к административной панели
     * - Управление пользователями (удаление, изменение ролей)
     * - Модерация любого контента
     * - Управление жанрами и категориями
     *
     * @security Назначается другим администратором в админ панели
     *           Authority: "ROLE_ADMIN"
     */
    ADMIN("ROLE_ADMIN");

    /**
     * Строковое представление роли для Spring Security.
     * Используется в:
     * - Аннотациях @PreAuthorize, @Secured
     * - Методах hasRole()
     * - Конфигурации HttpSecurity
     * @see org.springframework.security.access.prepost.PreAuthorize
     */
    private final String authority;
}
