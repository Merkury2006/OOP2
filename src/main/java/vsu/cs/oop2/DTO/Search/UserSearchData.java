package vsu.cs.oop2.DTO.Search;

import lombok.Builder;
import lombok.Data;

import java.util.List;
/**
 * DTO для передачи результатов поиска пользователей.
 * Содержит список найденных пользователей и метаданные поиска.
 *
 * Используется в административных панелях
 * @see UserData
 * @see vsu.cs.oop2.Services.UserService#searchUsers
 */
@Data
@Builder
public class UserSearchData {
    /**
     * Список найденных пользователей, соответствующих критериям поиска.
     * Каждый элемент содержит основные публичные данные о пользователе.
     */
    private List<UserData> users;

    /**
     * Общее количество пользователей, соответствующих критериям поиска.
     */
    private long totalUsers;

    /**
     * Количество пользователей с подтвержденным email среди найденных.
     * Полезная метрика для администраторов и анализа качества данных.
     */
    private long verifiedUsers;

    /**
     * Идентификатор текущего пользователя, выполняющего поиск.
     * Используется для:
     * - Выделения текущего пользователя в результатах
     * - Предотврачения определенных действий над собой
     */
    private Long currentUserId;
}
