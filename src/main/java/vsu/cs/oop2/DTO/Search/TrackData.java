package vsu.cs.oop2.DTO.Search;

import lombok.Builder;
import lombok.Data;

/**
 * DTO для передачи данных о музыкальном треке.
 * Используется для отображения информации о треках в результатах поиска,
 *
 * DTO содержит только необходимые для отображения поля,
 * исключая чувствительные или избыточные данные из сущности Track.
 *
 * @see vsu.cs.oop2.Entity.Track
 * @see TrackSearchData
 */
@Data
@Builder
public class TrackData {
    /**
     * Уникальный идентификатор трека в системе.
     * @apiNote Не может быть null для существующих треков.
     */
    private Long id;

    /**
     * Название музыкального трека.
     * Отображается пользователю в интерфейсе.
     */
    private String title;

    /**
     * Исполнитель или группа, создавшая трек.
     * Может быть как конкретным артистом, так и названием группы.
     */
    private String artist;

    /**
     * Музыкальный жанр трека.
     * Используется для фильтрации и категоризации контента.
     * Примеры: "Rock", "Pop", "Hip-Hop", "Classical", "Jazz"
     */
    private String genre;

    /**
     * Количество лайков (лайков) у трека.
     * Показывает популярность трека среди пользователей.
     */
    private Integer likeCount;

    /**
     * Идентификатор пользователя, создавшего или загрузившего трек.
     * Используется для:
     * - Отображения авторства
     */
    private Long userId;
}
