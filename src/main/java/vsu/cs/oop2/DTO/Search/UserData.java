package vsu.cs.oop2.DTO.Search;

import lombok.Builder;
import lombok.Data;

/**
 * DTO для передачи данных о пользователе.
 * Используется для отображения информации о пользователях в результатах поиска,
 * списках администраторов, и других местах без раскрытия чувствительных данных.
 *
 * Содержит только публичную информацию о пользователе, доступную другим пользователям.
 * Исключает пароли, токены и другую приватную информацию.
 *
 * @see vsu.cs.oop2.Entity.User
 * @see UserSearchData
 */
@Data
@Builder
public class UserData {
    /**
     * Уникальный идентификатор пользователя в системе.
     * Используется для идентификации и ссылок на профиль.
     */
    private Long id;

    /**
     * Имя пользователя для отображения.
     */
    private String username;

    /**
     * Email адрес пользователя для идентификации.
     * @security Не отображается публично по умолчанию для защиты приватности.
     */
    private String email;

    /**
     * Роль пользователя в системе.
     * Определяет уровень доступа и возможности.
     *
     * Возможные значения:
     * - "USER" - обычный пользователь (по умолчанию)
     * - "ADMIN" - администратор системы
     *
     * @see vsu.cs.oop2.Entity.UserRole
     */
    private String role;

    /**
     * Флаг подтверждения email адреса.
     * Показывает, прошел ли пользователь верификацию email.
     * @see vsu.cs.oop2.Services.EmailVerificationService
     */
    private boolean emailVerified;
}
